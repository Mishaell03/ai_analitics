-- МЕДИАФАЙЛЫ КУРСОВ И УРОКОВ
--
-- Файлы лежат в приватном баке MinIO. В базе хранится логический
-- идентификатор (media_key / file_id) и физический ключ объекта.
-- presigned URL в базе не хранится: он выдаётся по запросу.


-- ОБЛОЖКА КУРСА
CREATE TABLE IF NOT EXISTS course_images (
    image_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    course_id INTEGER NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,

    -- логический идентификатор файла, не зависит от пути в MinIO
    file_id VARCHAR(64) NOT NULL UNIQUE,

    -- физический ключ объекта в MinIO
    object_key VARCHAR(512) NOT NULL,

    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,

    width INTEGER NOT NULL,
    height INTEGER NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- у курса одна обложка
    UNIQUE (course_id)
);

CREATE INDEX IF NOT EXISTS ix_course_images_course_id ON course_images(course_id);


-- МЕДИАФАЙЛЫ (ИЗОБРАЖЕНИЯ И ВИДЕО)
CREATE TABLE IF NOT EXISTS media_files (
    media_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- стабильный логический идентификатор, используется в Markdown:
    -- ![описание](asset:media_key)
    media_key VARCHAR(64) NOT NULL UNIQUE,

    course_id INTEGER NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,

    -- физический ключ объекта в MinIO
    object_key VARCHAR(512) NOT NULL,

    -- image | video
    kind VARCHAR(16) NOT NULL,

    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,

    -- разрешение (для изображений и видео)
    width INTEGER,
    height INTEGER,

    -- длительность видео в секундах
    duration_seconds NUMERIC(10, 3),

    -- кодеки видео и аудио
    video_codec VARCHAR(32),
    audio_codec VARCHAR(32),

    -- имя файла, которое загрузил пользователь
    original_name VARCHAR(255),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_media_files_course_id ON media_files(course_id);


-- СВЯЗЬ МЕДИАФАЙЛОВ С УРОКАМИ
--
-- Один файл может использоваться в нескольких уроках курса,
-- поэтому связь хранится отдельно от самого файла.
CREATE TABLE IF NOT EXISTS lesson_media (
    lesson_id INTEGER NOT NULL REFERENCES lessons(lesson_id) ON DELETE CASCADE,
    media_id INTEGER NOT NULL REFERENCES media_files(media_id) ON DELETE CASCADE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (lesson_id, media_id)
);

CREATE INDEX IF NOT EXISTS ix_lesson_media_media_id ON lesson_media(media_id);
