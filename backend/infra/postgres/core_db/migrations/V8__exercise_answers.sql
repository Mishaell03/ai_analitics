-- ПРАВИЛЬНЫЕ ОТВЕТЫ НА ЗАДАНИЯ УРОКОВ
--
-- Задания (тесты) хранятся в Markdown урока, правильные ответы —
-- отдельно в базе. Связь идёт через стабильный exercise_id,
-- который указан в Markdown:
--
--     :::test
--     id: python-variables
--     Текст задания
--     :::
--
-- Урок может не содержать заданий, поэтому ответы необязательны.
CREATE TABLE IF NOT EXISTS exercise_answers (
    answer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    lesson_id INTEGER NOT NULL REFERENCES lessons(lesson_id) ON DELETE CASCADE,

    -- идентификатор задания из Markdown урока
    exercise_id VARCHAR(64) NOT NULL,

    answer TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- у задания урока один правильный ответ
    UNIQUE (lesson_id, exercise_id)
);

CREATE INDEX IF NOT EXISTS ix_exercise_answers_lesson_id ON exercise_answers(lesson_id);
