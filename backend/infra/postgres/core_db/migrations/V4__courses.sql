-- COURSES
CREATE TABLE IF NOT EXISTS courses (
    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    slug VARCHAR(255) NOT NULL UNIQUE,

    title VARCHAR(255) NOT NULL,
    description TEXT,

    is_published BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- MODULES OF COURSE
CREATE TABLE IF NOT EXISTS course_modules (
    module_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    course_id INTEGER NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,

    title VARCHAR(255) NOT NULL,
    description TEXT,

    position INTEGER NOT NULL,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE(course_id, position)
);

CREATE INDEX IF NOT EXISTS ix_course_modules_course_id ON course_modules(course_id);


-- LESSONS
CREATE TABLE IF NOT EXISTS lessons (
    lesson_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    module_id INTEGER NOT NULL REFERENCES course_modules(module_id) ON DELETE CASCADE,

    title VARCHAR(255) NOT NULL,
    description TEXT,
    answer TEXT,

    position INTEGER NOT NULL,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE(module_id, position)
);

CREATE INDEX IF NOT EXISTS ix_lessons_module_id ON lessons(module_id);