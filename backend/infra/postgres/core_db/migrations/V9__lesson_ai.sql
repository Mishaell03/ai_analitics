-- Диалог принадлежит пользователю и конкретному уроку.
CREATE TABLE ai_conversations (
    conversation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    lesson_id INTEGER NOT NULL REFERENCES lessons(lesson_id) ON DELETE CASCADE,
    summary TEXT NOT NULL DEFAULT '',
    active_request UUID,
    busy_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, lesson_id)
);

CREATE TABLE ai_questions (
    question_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id INTEGER NOT NULL REFERENCES ai_conversations(conversation_id) ON DELETE CASCADE,
    request_id UUID NOT NULL,
    question TEXT NOT NULL,
    user_context TEXT NOT NULL DEFAULT '',
    context_snapshot JSONB NOT NULL,
    prompt_hash VARCHAR(64) NOT NULL,
    model VARCHAR(100) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'completed', 'refused', 'failed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (conversation_id, request_id)
);
CREATE INDEX ix_ai_questions_conversation_created ON ai_questions(conversation_id, created_at);

-- Необработанный ответ провайдера хранится отдельно и не выдаётся ученику.
CREATE TABLE ai_answers (
    answer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INTEGER NOT NULL UNIQUE REFERENCES ai_questions(question_id) ON DELETE CASCADE,
    answer TEXT NOT NULL,
    provider_response JSONB,
    error_code VARCHAR(64),
    input_tokens INTEGER NOT NULL DEFAULT 0 CHECK (input_tokens >= 0),
    output_tokens INTEGER NOT NULL DEFAULT 0 CHECK (output_tokens >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
