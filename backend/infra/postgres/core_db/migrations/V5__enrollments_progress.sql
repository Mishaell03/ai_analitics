-- COURSE ENROLLMENTS
CREATE TABLE IF NOT EXISTS course_enrollments (
    enrollment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    course_id INTEGER NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(user_id, course_id)
);

CREATE INDEX IF NOT EXISTS ix_course_enrollments_course_id ON course_enrollments(course_id);

CREATE TABLE IF NOT EXISTS lesson_attempts (
    attempt_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    lesson_id INTEGER NOT NULL REFERENCES lessons(lesson_id) ON DELETE CASCADE,

    -- SQL query of the user (NULL for tests)
    code TEXT,
    -- answers of the test (NULL for SQL tasks)
    answers JSONB,

    -- 0 - wrong, 1 - medium, 2 - high, 3 - correct
    correctness SMALLINT NOT NULL CHECK (correctness BETWEEN 0 AND 3),
    -- 0 - slow, 1 - medium, 2 - high
    speed SMALLINT NOT NULL CHECK (speed BETWEEN 0 AND 2),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_lesson_attempts_user_lesson ON lesson_attempts(user_id, lesson_id);