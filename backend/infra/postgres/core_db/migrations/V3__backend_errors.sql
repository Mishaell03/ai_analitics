CREATE TABLE IF NOT EXISTS backend_errors (
    code VARCHAR(32) PRIMARY KEY,
    http_status INT NOT NULL
);

CREATE TABLE IF NOT EXISTS backend_errors_localization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL REFERENCES backend_errors(code) ON DELETE CASCADE,
    language VARCHAR(3) NOT NULL,
    message VARCHAR(255),
    UNIQUE(code, language)
);

CREATE TABLE IF NOT EXISTS users_event_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(user_id) ON DELETE CASCADE,
    session_id INTEGER REFERENCES users_sessions(id) ON DELETE CASCADE,
    event VARCHAR(255) NOT NULL,
    status_code INTEGER,
    request_method VARCHAR(16) NOT NULL,
    request_path VARCHAR(255) NOT NULL,
    ip_address INET NOT NULL,
    country_code VARCHAR(3),
    is_proxy BOOLEAN,
    device_id VARCHAR(255),
    platform VARCHAR(10),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_users_event_logs_user_id ON users_event_logs(user_id);
CREATE INDEX IF NOT EXISTS ix_users_event_logs_session_id ON users_event_logs(session_id);
CREATE INDEX IF NOT EXISTS ix_users_event_logs_event ON users_event_logs(event);
CREATE INDEX IF NOT EXISTS ix_users_event_logs_ip_address ON users_event_logs(ip_address);
CREATE INDEX IF NOT EXISTS ix_users_event_logs_device_id ON users_event_logs(device_id);
CREATE INDEX IF NOT EXISTS ix_users_event_logs_created_at ON users_event_logs(created_at);
