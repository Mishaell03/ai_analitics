CREATE TABLE IF NOT EXISTS providers (
    code VARCHAR(20) PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS user_auth_methods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL
        REFERENCES users(user_id)
        ON DELETE CASCADE,
    provider VARCHAR(32) NOT NULL REFERENCES providers(code) ON DELETE RESTRICT,
    provider_user_id VARCHAR(255),
    password_hash VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (provider, provider_user_id)
);

CREATE TABLE IF NOT EXISTS users_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(255) NOT NULL,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    session VARCHAR(255) NOT NULL UNIQUE,
    ip INET,
    language VARCHAR(3) NOT NULL,
    provider VARCHAR(20) NOT NULL REFERENCES providers(code) ON DELETE RESTRICT,
    platform VARCHAR(15),
    device_name VARCHAR(32),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_users_sessions_user_id ON users_sessions (user_id);
CREATE INDEX IF NOT EXISTS ix_users_sessions_device_id ON users_sessions (device_id);
CREATE INDEX IF NOT EXISTS ix_users_sessions_expires_at ON users_sessions (expires_at);
