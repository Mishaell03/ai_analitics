-- СОГЛАСИЯ НА ОБРАБОТКУ ДАННЫХ
CREATE TABLE IF NOT EXISTS users_consents (
    consent_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,

    -- PERSONAL_DATA, MARKETING, ANALYTICS
    consent_code VARCHAR(64) NOT NULL,
    is_accepted BOOLEAN NOT NULL,

    -- версия документа, с которым пользователь согласился
    policy_version VARCHAR(20) NOT NULL DEFAULT '1.0',

    -- IP, с которого было дано согласие
    ip INET,

    -- момент, когда согласие было принято или отозвано
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (user_id, consent_code)
);

CREATE INDEX IF NOT EXISTS ix_users_consents_user_id ON users_consents(user_id);
CREATE INDEX IF NOT EXISTS ix_users_consents_consent_code ON users_consents(consent_code);