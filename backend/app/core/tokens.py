"""ХЭШИРОВАНИЕ СЕССИОННЫХ ТОКЕНОВ

В базе данных хранится исключительно SHA-256 хэш сессионного токена.
Сам секретный токен остаётся только в cookie браузера у клиента.
Утечка дампа БД не позволяет авторизоваться, так как значение хэша из БД
не может быть использовано вместо сырого токена (хэш хэша не совпадает с хэшем).
"""

import hashlib


def hash_session_token(token: str) -> str:
    """SHA-256 токена в hex: 64 символа, помещается в VARCHAR(255)."""
    return hashlib.sha256(token.strip().encode("utf-8")).hexdigest()


def token_candidates(token: str) -> tuple[str, ...]:
    """Возвращает безопасный идентификатор для поиска сессии в БД (строго SHA-256).

    Сырой токен намеренно не возвращается: совпадение по нехэшированному
    значению запрещено, чтобы исключить использование хэша из дампа БД.
    """
    return (hash_session_token(token),)
